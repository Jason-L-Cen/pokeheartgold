"""Prepare deterministic Python-integer goldens for the original CPS arithmetic."""
import math
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[2]


def prepare(output):
    rng = random.Random(0x48474249)
    arithmetic = []
    for bits in (1, 16, 31, 48, 64, 127, 128, 255, 256, 511, 512, 1024):
        digits = (bits + 15)//16 + 2
        a = (1 << bits)-1
        b = rng.randrange(1, 1 << bits)
        pairs = [(a,b),(b,a)]
        if bits==1: pairs.append((0,1))
        if bits==16: pairs.append((1,1 << 16))
        for left,right in pairs:
            modulus = 1 << (16*digits)
            small = rng.choice((0,1,0xFFFF))
            quotient,remainder = divmod(left,right)
            arithmetic.append(dict(digits=digits,small=small,a=left,b=right,
                added=(left+right)%modulus,subtracted=(left-right)%modulus,
                multiplied=(left*right)%modulus,squared=(left*left)%modulus,
                negated=(-left)%modulus,quotient=quotient,remainder=remainder,
                scaled=(left*small)%modulus))
    powers = []
    for i,bits in enumerate((8,16,31,64,127,256,512,1024)):
        modulus = rng.getrandbits(bits) | (1 << (bits-1)) | 1
        base = rng.randrange(2,modulus)
        while math.gcd(base,modulus)!=1:
            base = base+1 if base+1<modulus else 2
        exponent = (0,1,3,65537)[i%4]
        if exponent >= 1 << (16*((bits+15)//16)): exponent = 3
        powers.append(dict(digits=2*((bits+15)//16)+1,base=base,exponent=exponent,
            modulus=modulus,result=pow(base,exponent,modulus),inverse=pow(base,-1,modulus)))

    def words(value,digits):
        return '{'+','.join(str((value >> (16*i)) & 0xFFFF) for i in range(digits))+'}'

    maximum = max(record['digits'] for record in arithmetic+powers)
    lines = ['// Generated by prepare_bignum_checks.py; Python integers are the oracle.',
             f'enum {{ HG_BIG_MAX_DIGITS = {maximum} }};']
    for name,records,scalars in [('Arithmetic',arithmetic,('digits','small')),('Power',powers,('digits',))]:
        arrays = [field for field in records[0] if field not in scalars]
        lines += ['typedef struct { int '+','.join(scalars)+'; u16 '+
                  ','.join(field+'[HG_BIG_MAX_DIGITS]' for field in arrays)+'; } HGBig'+name+';',
                  'static const HGBig'+name+' hgBig'+name+'[]={']
        for record in records:
            values = [str(record[field]) if field in scalars else words(record[field],record['digits']) for field in record]
            lines.append('{'+','.join(values)+'},')
        lines.append('};')
    output = Path(output); output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('\n'.join(lines)+'\n')
    print(f'Prepared CPS goldens: {len(arithmetic)} arithmetic and {len(powers)} modular-power/inverse cases, through 1024 bits.')


if __name__ == '__main__':
    prepare(ROOT/'ios/build-original-host/include/hg_bignum_checks.h')
